// Database types for Student Connect application
// Developed with assistance from AI tools.

export interface profiles {
  id: string;
  role: "user" | "admin";
  email: string;
}

export interface job_postings {
  id: string;
  title: string;
  description: string;
  /** Foreign key referencing companies.name — links a job posting to a company */
  company: string;
  application_url: string;
  created_by: string;
}

export interface event_registration {
  id: string;
  event_id: string;
  user_id: string;
}

export interface events {
  id: string;
  title: string;
  description: string;
  location: string;
  start_time: string;
  end_time: string;
  created_by: string;
  /** Foreign key referencing companies.name — links an event to a company */
  company: string;
}

export interface companies {
  id: string;
  name: string;
  description: string;
  website_url: string;
}


// For creating new entries, we can omit the id field since it will be generated by the database
export interface create_event_input {
  title: string;
  description: string;
  location: string;
  start_time: string;
  end_time: string;
}

export interface create_job_input {
  title: string;
  description: string;
  company: string;
  application_url: string;
}

export interface create_company_input {
  name: string;
  description: string;
  website_url: string;
}