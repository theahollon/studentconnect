// Database types for Student Connect application

export interface profiles {
  id: string;
  role: "user" | "admin";
  email: string;
}

export interface job_postings {
  id: string;
  title: string;
  description: string;
  company: string;
  application_url: string;
  created_by: string;

}

export interface event_registration {
  id: string;
  event_id: string;
  user_id: string;
}

export interface event_favorite {
  id: string;
  user_id: string;
  event_id: string;
  created_at: string;
}

export interface job_favorite {
  id: string;
  user_id: string;
  job_id: string;
  created_at: string;
}

export interface events {
  id: string;
  title: string;
  description: string;
  location: string;
  start_time: string;
  end_time: string;
  created_by: string;
}


// For creating new entries, we can omit the id field since it will be generated by the database
export interface create_event_input {
  title: string;
  description: string;
  location: string;
  start_time: string;
  end_time: string;
}

export interface create_job_input {
  title: string;
  description: string;
  company: string;
  application_url: string;
}

export type FavoriteEvent = Pick<
  events,
  "id" | "title" | "description" | "location" | "start_time"
>;

export type FavoriteJob = Pick<
  job_postings,
  "id" | "title" | "description" | "company"
>;

export interface EventFavoriteRow {
  events: FavoriteEvent | FavoriteEvent[] | null;
}

export interface JobFavoriteRow {
  job_postings: FavoriteJob | FavoriteJob[] | null;
}
