import { Timestamp } from "next/dist/server/lib/cache-handlers/types";

export interface profiles {
  id: string;
  role: "user" | "admin";
  email: string;
  strikes: number;
  banned_until: string | null;
  study_program: string | null;

}

export interface user_allergies {
  id: string;
  user_id: string;
  allergy: string;
}

export interface job_postings {
  id: string;
  title: string;
  description: string;
  /** Foreign key referencing companies.name — links a job posting to a company */
  company: string;
  application_url: string;
  created_by: string;
  employment_type: string;

}

export interface event_registration {
  id: string;
  event_id: string;
  user_id: string;
}

export interface event_review {
  id: string;
  event_id: string;
  user_id: string;
  rating: number;
  comment: string;
  created_at: string;
  updated_at: string;
}

export interface event_review_with_profile extends event_review {
  profiles?: {
    email: string;
  } | null;
}

export interface event_favorite {
  id: string;
  user_id: string;
  event_id: string;
  created_at: string;
}

export interface job_favorite {
  id: string;
  user_id: string;
  job_id: string;
  created_at: string;
}

export interface events {
  id: string;
  title: string;
  description: string;
  location: string;
  start_time: string;
  end_time: string;
  created_by: string;
  /** Foreign key referencing companies.name — links an event to a company */
  company: string;
}

export interface companies {
  id: string;
  name: string;
  description: string;
  website_url: string;
}


// For creating new entries, we can omit the id field since it will be generated by the database
export interface create_event_input {
  title: string;
  description: string;
  location: string | null;
  start_time: string | null;
  end_time: string | null;
  //Here we need created_by and created_at. If we want to use this!
  event_type: string | null;
  company?: string | null;
}

export interface create_job_input {
  title: string;
  description: string | null;
  company: string;
  application_url: string;
  
    location: string | null;
  application_deadline: string | null;
  employment_type: string | null;
  contact_email: string | null;
}

export interface create_company_input {
  name: string;
  description: string;
  website_url: string;
}

export type FavoriteEvent = Pick<
  events,
  "id" | "title" | "description" | "location" | "start_time"
>;

export type FavoriteJob = Pick<
  job_postings,
  "id" | "title" | "description" | "company"
>;

export interface create_event_review_input {
  event_id: string;
  user_id: string;
  rating: number;
  comment: string;
}

export interface EventFavoriteRow {
  events: FavoriteEvent | FavoriteEvent[] | null;
}

export interface JobFavoriteRow {
  job_postings: FavoriteJob | FavoriteJob[] | null;
}

