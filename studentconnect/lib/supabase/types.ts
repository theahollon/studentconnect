// Database types for Student Connect application

export interface profiles {
  id: string;
  role: "user" | "admin";
  email: string;
}

export interface job_postings {
  id: string;
  title: string;
  description: string;
  company: string;
  application_url: string;
  created_by: string;
  employment_type: string;

}

export interface event_registration {
  id: string;
  event_id: string;
  user_id: string;
}

export interface events {
  id: string;
  title: string;
  description: string;
  location: string;
  start_time: string;
  end_time: string;
  created_by: string;
  event_type: string;
}


// For creating new entries, we can omit the id field since it will be generated by the database
export interface create_event_input {
  title: string;
  description: string;
  location: string | null;
  start_time: string | null;
  end_time: string | null;
  //Here we need created_by and created_at. If we want to use this!
  event_type: string | null;
}

export interface create_job_input {
  title: string;
  description: string | null;
  company: string;
  application_url: string;
  location: string | null;
  application_deadline: string | null, 
  employment_type: string | null,
  contact_email: string  | null,
}